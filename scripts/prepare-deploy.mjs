// Writes .env.vercel: the production environment variables, ready to paste into
// Vercel (Project -> Settings -> Environment Variables -> paste). Values come from
// .env.local; CRON_SECRET is a new production-only secret (kept if .env.vercel
// already has one, so Vercel and Supabase stay in step). Prints names only.
// Run: npm run deploy:env
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";

function parse(path) {
  const out = {};
  if (!existsSync(path)) return out;
  for (const line of readFileSync(path, "utf8").split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/);
    if (m) out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, "$2"); // later lines win
  }
  return out;
}

const local = parse(".env.local");
const previous = parse(".env.vercel");

const fromLocal = ["NEXT_PUBLIC_SUPABASE_URL", "NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY", "DATABASE_URL", "EODHD_API_KEY"];
const missing = fromLocal.filter((k) => !local[k]);
if (missing.length) {
  console.error(`Missing in .env.local: ${missing.join(", ")}`);
  process.exit(1);
}

const env = {
  ...Object.fromEntries(fromLocal.map((k) => [k, local[k]])),
  MARKET_DATA_SOURCE: "eodhd",
  EODHD_DAILY_LIMIT: local.EODHD_DAILY_LIMIT || "15",
  EODHD_QUOTE_MODE: local.EODHD_QUOTE_MODE || "eod",
  PRICE_REFRESH_MINUTES: local.PRICE_REFRESH_MINUTES || "30",
  PRICE_REFRESH_SCOPE: local.PRICE_REFRESH_SCOPE || "holdings",
  EOD_PUBLISH_DELAY_MINUTES: local.EOD_PUBLISH_DELAY_MINUTES || "120",
  CRON_SECRET: previous.CRON_SECRET || randomBytes(32).toString("base64url"),
};

const text = [
  "# Production environment for Vercel. GENERATED by `npm run deploy:env`. Contains secrets: never commit or share.",
  "# Not included on purpose: SUPABASE_SECRET_KEY and DIRECT_URL (not used by the running app), DEV_USER_* (local test login).",
  "# JOBS_BASE_URL is not needed on Vercel: the app uses VERCEL_PROJECT_PRODUCTION_URL.",
  ...Object.entries(env).map(([k, v]) => `${k}=${v}`),
  "",
].join("\n");
writeFileSync(".env.vercel", text, { mode: 0o600 });

console.log(`Wrote .env.vercel with ${Object.keys(env).length} variables:`);
for (const k of Object.keys(env)) console.log(`  ${k}${k === "CRON_SECRET" && !previous.CRON_SECRET ? " (new production secret)" : ""}`);
